/**
 * Export a compliance report as a PDF document.
 * Returns a Buffer containing the PDF file.
 */
export async function exportReportToPDF(
  report: ComplianceReport,
  metadata: ReportMetadata,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: PAGE_MARGIN, size: 'LETTER' });
    const chunks: Buffer[] = [];

    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('error', reject);
    doc.on('end', () => resolve(Buffer.concat(chunks)));

    const ctx: PDFRenderContext = { doc, y: PAGE_MARGIN };

    // Title
    const titleMap: Record<string, string> = {
      hipaa_audit: 'HIPAA Audit Report',
      soc2_security: 'SOC 2 Security Report',
      soc2_availability: 'SOC 2 Availability Report',
      consent_compliance: 'Consent Compliance Report',
      access_review: 'Access Review Report',
    };

    writeTitle(ctx, titleMap[report.reportType] ?? 'Compliance Report');

    // Metadata section
    renderMetadata(ctx, report, metadata);

    // Report-specific content
    switch (report.reportType) {
      case 'hipaa_audit':
        renderHIPAAAudit(ctx, report);
        break;
      case 'soc2_security':
        renderSOC2Security(ctx, report);
        break;
      case 'soc2_availability':
        renderSOC2Availability(ctx, report);
        break;
      case 'consent_compliance':
        renderConsentCompliance(ctx, report);
        break;
      case 'access_review':
        renderAccessReview(ctx, report);
        break;
      default: {
        const exhaustive: never = report;
        throw new Error(`Unsupported report type for PDF: ${JSON.stringify(exhaustive)}`);
      }
    }

    // Footer
    ensureSpace(ctx, 30);
    ctx.y += 20;
    ctx.doc.fontSize(8).font('Helvetica-Oblique');
    ctx.doc.text(
      `Generated by Pixelated Empathy Compliance Reporting | ${new Date().toISOString()}`,
      PAGE_MARGIN,
      ctx.y,
      { width: CONTENT_WIDTH, align: 'center' },
    );

    doc.end();
  });
}
