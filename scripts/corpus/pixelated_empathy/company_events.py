"""Clinical event spine — 12 months of training program events.

Defines the canonical sequence of clinical training events that anchor the
synthetic corpus: supervision sessions, case reviews, crisis simulations,
workshops, debriefs, and administrative milestones across a 12-month
clinical training curriculum at Pixelated Empathy.

Each event is a ClinicalEvent with de-identified case references, clinical
topics, and participant lists drawn from the 9-persona clinical team.
"""

from __future__ import annotations

from datetime import datetime, timezone

from pixelated_empathy.schemas import ClinicalEvent, EventSpine


def _evt(
    year: int,
    month: int,
    day: int,
    hour: int,
    minute: int,
    seq: int,
    participants: list[str],
    summary: str,
    topics: list[str],
    event_type: str = "session",
) -> ClinicalEvent:
    return ClinicalEvent(
        id=f"EVT-{year:04d}-{seq:03d}",
        date=datetime(year, month, day, hour, minute, tzinfo=timezone.utc),
        participants=participants,
        summary=summary,
        topics=topics,
        event_type=event_type,
    )


