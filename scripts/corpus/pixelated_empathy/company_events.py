def _build_spine() -> EventSpine:
    events: list[CompanyEvent] = []
    for raw in _RAW:
        events.append(
            CompanyEvent(
                id=str(raw["id"]),
                date=datetime.fromisoformat(str(raw["date"]).replace("Z", "+00:00")),
                participants=[str(p) for p in raw["participants"]],  # type: ignore[arg-type]
                summary=str(raw["summary"]),
                topics=[str(t) for t in raw["topics"]],  # type: ignore[arg-type]
            )
        )
    return EventSpine(events=events)


EVENT_SPINE: EventSpine = _build_spine()


def get_event_spine() -> EventSpine:
    """Return the canonical event spine."""
    return EVENT_SPINE
