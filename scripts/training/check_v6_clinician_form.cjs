const { chromium } = require('@playwright/test');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const os = require('node:os');
const path = require('node:path');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'paige-form-test-'));
const testFile = name => path.join(scratch, name);
(async () => {
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage();
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 let httpRequests=0;page.on('request',r=>{if(/^https?:/.test(r.url()))httpRequests++;});
 const file=path.resolve(process.argv[2]);
 await page.goto('file://'+file);
 await page.getByRole('button',{name:'Export completed assessment',exact:true}).click();
 assert.match(await page.locator('#notice').textContent(),/Not exported/);
 await page.locator('#A-rating_status').selectOption(JSON.stringify('rated'));
 for (const key of ['safety','accuracy_and_role','support_and_relevance','actionability_and_concision']) await page.locator('#A-'+key).selectOption('2');
 await page.locator('#A-critical_failure').selectOption('false');
 await page.locator('#A-evidence').fill('SYNTHETIC BROWSER TEST excerpt');
 await page.locator('#A-rationale').fill('SYNTHETIC BROWSER TEST rationale');
 const download1=page.waitForEvent('download');await page.locator('#save').click();
 const draft=await download1;await draft.saveAs(testFile('paige-browser-test-draft.json'));
 const data=JSON.parse(fs.readFileSync(testFile('paige-browser-test-draft.json'),'utf8'));
 assert.equal(data.ratings['qualified-review-000'].A.dimension_scores.safety,2);
 assert.equal(data.status,'draft');assert.equal(data.completed_at,null);
 await page.reload();assert.equal(await page.locator('#A-rationale').inputValue(),'SYNTHETIC BROWSER TEST rationale');
 await page.locator('#loadFile').setInputFiles(testFile('paige-browser-test-draft.json'));
 await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Saved answers loaded.');
 await page.locator('#caseSelect').selectOption('44');
 await page.locator('#A-rating_status').selectOption(JSON.stringify('rated'));
 await page.locator('#A-task_met').selectOption('true');
 await page.locator('#A-acknowledgment_applicable').selectOption('true');
 await page.locator('#A-acknowledgment_met').selectOption('true');
 await page.locator('#A-acknowledgment_applicable').selectOption('false');
 assert.equal(await page.locator('#A-acknowledgment_met').count(),0);
 assert.equal(await page.evaluate("state.ratings['followup-review-001'].A.acknowledgment_met"),null);
 await page.locator('#A-critical_concern').selectOption('false');
 await page.locator('#A-evidence').fill('SYNTHETIC TEST');await page.locator('#A-rationale').fill('SYNTHETIC TEST');
 // Test the supported unratable path on all remaining responses, without inventing clinical judgments.
 await page.evaluate(`for(const p of DATA.packets){for(const c of ['A','B']){const r=state.ratings[p.packet_id][c];r.rating_status='unratable';r.rationale='SYNTHETIC BROWSER TEST: not a clinician assessment';}if(p.section==='original')state.pair_preferences[p.packet_id]={preference:'unratable',rationale:'SYNTHETIC BROWSER TEST'};}render();`);
 const download2=page.waitForEvent('download');await page.locator('#export').click();await (await download2).saveAs(testFile('paige-browser-test-completed.json'));
 const final=JSON.parse(fs.readFileSync(testFile('paige-browser-test-completed.json'),'utf8'));
 assert.equal(final.status,'submitted');assert.ok(final.completed_at);assert.equal(final.unratable_responses,136);
 assert.equal(final.ratings['qualified-review-000'].A.critical_failure,null);
 assert.equal(final.ratings['qualified-review-000'].A.dimension_scores.safety,null);
 assert.equal(final.ratings['followup-review-001'].A.task_met,null);
 assert.equal(Object.keys(final.ratings).length,68);assert.equal(Object.keys(final.pair_preferences).length,44);
 // A wrong evidence binding must never replace the loaded assessment.
 data.packet_sha256['original-rubric.json']='incorrect';
 fs.writeFileSync(testFile('paige-browser-invalid.json'),JSON.stringify(data));
 page.on('dialog',d=>d.accept());await page.locator('#loadFile').setInputFiles(testFile('paige-browser-invalid.json'));
 await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('different review materials'));
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:testFile('paige-review-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);assert.equal(httpRequests,0);
 console.log(JSON.stringify({browser:'Chromium',passed:true,cases:68,responses:136,externalRequests:httpRequests,checks:['missing-answer guard','original scores','draft download','local recovery','draft import','conditional acknowledgment','unratable export','all blind IDs','evidence mismatch rejection','mobile width']}));
 await browser.close();
 fs.rmSync(scratch,{recursive:true,force:true});
})().catch(e=>{console.error(e);process.exit(1);});
